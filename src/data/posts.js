/** Bitta maqola + «O'xshash maqolalar» (related) */
export function getPost(slug) {
  const post = posts.find((p) => p.slug === slug);
  if (!post) return null;
  const others = posts.filter((p) => p.slug !== slug);
  const same = others.filter((p) => p.category.slug === post.category.slug);
  return { ...post, related: [...same, ...others.filter((p) => !same.includes(p))].slice(0, 3) };
}
